package mcp

import (
	"context"
	"encoding/json"
	"net/http"

	"upwork-buddy/internal/server"

	"github.com/modelcontextprotocol/go-sdk/mcp"
)

type draftProposalInput struct {
	ID                   *uint    `json:"id,omitempty" jsonschema:"Existing proposal ID to update"`
	ProposalID           *uint    `json:"proposal_id,omitempty" jsonschema:"Alias for id"`
	JobID                any      `json:"job_id,omitempty" jsonschema:"Numeric DB job ID or Upwork ~jobID"`
	UpworkJobID          string   `json:"upwork_job_id,omitempty" jsonschema:"Upwork job ID (e.g. ~01abc)"`
	CoverLetter          string   `json:"cover_letter" jsonschema:"Proposal cover letter text"`
	BidType              string   `json:"bid_type,omitempty" jsonschema:"Bid type: hourly or fixed"`
	BidAmount            *float64 `json:"bid_amount,omitempty" jsonschema:"Hourly rate or fixed bid amount"`
	RateIncrease         string   `json:"rate_increase,omitempty" jsonschema:"Optional scheduled rate-increase option"`
	ConnectsRequired     *int     `json:"connects_required,omitempty" jsonschema:"Required connects for the job"`
	Milestones           any      `json:"milestones,omitempty" jsonschema:"Optional fixed-price milestones array"`
	MilestonesJSON       any      `json:"milestones_json,omitempty" jsonschema:"Alias for milestones"`
	ScreeningAnswers     any      `json:"screening_answers,omitempty" jsonschema:"Screening question answers (array of strings or objects)"`
	ScreeningAnswersJSON any      `json:"screening_answers_json,omitempty" jsonschema:"Alias for screening_answers"`
	BoostConnects        *int     `json:"boost_connects,omitempty" jsonschema:"Optional boost connects amount"`
	PortfolioRefs        any      `json:"portfolio_refs,omitempty" jsonschema:"Portfolio references array"`
	PortfolioRefsJSON    any      `json:"portfolio_refs_json,omitempty" jsonschema:"Alias for portfolio_refs"`
	Status               string   `json:"status,omitempty" jsonschema:"Initial or updated proposal status (default draft)"`
}

type fillProposalFormInput struct {
	ProposalID   uint   `json:"proposal_id" jsonschema:"Persisted proposal ID to fill on Upwork"`
	ApplyURL     string `json:"apply_url,omitempty" jsonschema:"Optional explicit Upwork apply URL"`
	RateIncrease string `json:"rate_increase,omitempty" jsonschema:"Optional rate-increase selector value"`
}

type submitProposalInput struct {
	ProposalID    uint   `json:"proposal_id" jsonschema:"Persisted proposal ID to submit"`
	ApprovalToken string `json:"approval_token,omitempty" jsonschema:"Single-use approval token generated by upwork_fill_proposal_form"`
	ApplyURL      string `json:"apply_url,omitempty" jsonschema:"Optional explicit Upwork apply URL"`
}

type syncProposalsInput struct{}

func toRawJSON(v any) (json.RawMessage, error) {
	if v == nil {
		return nil, nil
	}
	b, err := json.Marshal(v)
	if err != nil {
		return nil, err
	}
	return json.RawMessage(b), nil
}

func (s *Server) registerProposalTools() {
	mcp.AddTool(s.mcpServer, &mcp.Tool{
		Name:        "upwork_draft_proposal",
		Description: "Create or update a structured Upwork proposal draft (cover letter, bid rate, milestones, screening answers, portfolio refs) in Postgres.",
	}, func(ctx context.Context, _ *mcp.CallToolRequest, in draftProposalInput) (*mcp.CallToolResult, any, error) {
		propID := in.ID
		if propID == nil {
			propID = in.ProposalID
		}
		jobIDRaw, err := toRawJSON(in.JobID)
		if err != nil {
			return toolErrorResult(&server.ServiceError{Code: "INVALID_PARAMS", HTTPStatus: http.StatusBadRequest, Message: "invalid job_id"})
		}
		milestonesRaw, _ := toRawJSON(in.Milestones)
		milestonesJSONRaw, _ := toRawJSON(in.MilestonesJSON)
		screeningRaw, _ := toRawJSON(in.ScreeningAnswers)
		screeningJSONRaw, _ := toRawJSON(in.ScreeningAnswersJSON)
		portfolioRaw, _ := toRawJSON(in.PortfolioRefs)
		portfolioJSONRaw, _ := toRawJSON(in.PortfolioRefsJSON)

		entry, created, err := s.backend.SaveProposal(ctx, server.SaveProposalInput{
			ID:                   propID,
			JobID:                jobIDRaw,
			UpworkJobID:          in.UpworkJobID,
			CoverLetter:          in.CoverLetter,
			BidType:              in.BidType,
			BidAmount:            in.BidAmount,
			RateIncrease:         in.RateIncrease,
			ConnectsRequired:     in.ConnectsRequired,
			MilestonesJSON:       milestonesJSONRaw,
			Milestones:           milestonesRaw,
			ScreeningAnswersJSON: screeningJSONRaw,
			ScreeningAnswers:     screeningRaw,
			BoostConnects:        in.BoostConnects,
			PortfolioRefsJSON:    portfolioJSONRaw,
			PortfolioRefs:        portfolioRaw,
			Status:               in.Status,
		}, "mcp")
		if err != nil {
			return toolErrorResult(err)
		}
		return toolSuccess(map[string]any{
			"proposal_id": entry.ID,
			"id":          entry.ID,
			"status":      entry.Status,
			"proposal":    entry,
			"created":     created,
		})
	})

	mcp.AddTool(s.mcpServer, &mcp.Tool{
		Name:        "upwork_fill_proposal_form",
		Description: "Fill the live Upwork proposal apply form in Chrome, verify DOM read-back, check connects sufficiency, and queue as pending_approval with an approval_token.",
	}, func(ctx context.Context, _ *mcp.CallToolRequest, in fillProposalFormInput) (*mcp.CallToolResult, any, error) {
		res, err := s.backend.FillProposal(ctx, uint64(in.ProposalID), server.FillProposalInput{
			ApplyURL:     in.ApplyURL,
			RateIncrease: in.RateIncrease,
		})
		if err != nil {
			return toolErrorResult(err)
		}
		return toolSuccess(res)
	})

	mcp.AddTool(s.mcpServer, &mcp.Tool{
		Name:        "upwork_submit_proposal",
		Description: "Submit an approved or policy-eligible proposal on Upwork, enforcing policy mode (confirm_in_ui, draft_only, auto_with_guardrails), daily caps, and screening answers.",
	}, func(ctx context.Context, _ *mcp.CallToolRequest, in submitProposalInput) (*mcp.CallToolResult, any, error) {
		res, err := s.backend.CommitProposal(ctx, uint64(in.ProposalID), server.CommitProposalInput{
			ApprovalToken: in.ApprovalToken,
			ApplyURL:      in.ApplyURL,
		}, false)
		if err != nil {
			return toolErrorResult(err)
		}
		return toolSuccess(res)
	})

	mcp.AddTool(s.mcpServer, &mcp.Tool{
		Name:        "upwork_sync_proposals",
		Description: "Scrape /nx/proposals/ via Chrome and sync proposal statuses (submitted, viewed, interviewing, offer, archived) into Postgres.",
	}, func(ctx context.Context, _ *mcp.CallToolRequest, _ syncProposalsInput) (*mcp.CallToolResult, any, error) {
		res, err := s.backend.SyncProposals(ctx)
		if err != nil {
			return toolErrorResult(err)
		}
		return toolSuccess(res)
	})
}
